//! Opt-in, cache-only Siso REAPI action cache for local Chromium compiles.
//!
//! Every action still runs locally. Siso looks up clang compile results in a
//! loopback REAPI action cache, and uploads results it produced itself. Release
//! packaging never uses a cache-mode output directory.

use anyhow::{Context, Result, bail, ensure};
use serde_json::{Value, json};
use std::ffi::OsString;
use std::fs;
use std::net::{SocketAddr, TcpStream};
use std::path::Path;
use std::process::Command;
use std::time::Duration;

pub(super) const ADDRESS_VARIABLE: &str = "STAINLESS_REAPI_ADDRESS";
pub(super) const INSTANCE_VARIABLE: &str = "STAINLESS_REAPI_INSTANCE";
pub(super) const OFFLINE_OUTPUT: &str = "out/Stainless";
pub(super) const CACHE_OUTPUT: &str = "out/StainlessCache";
pub(super) const MARKER: &str = "stainless-reapi-cache.json";
const DEFAULT_INSTANCE: &str = "stainless";
const SCHEMA: u32 = 1;
const OFFLINE_ARGS_LINE: &str = "use_remoteexec = false";
const CACHE_ARGS_LINE: &str = "use_remoteexec = true";
const REWRAPPER_CONFIG: &str = "buildtools/reclient_cfgs/chromium-browser-clang/rewrapper_mac.cfg";
const BACKEND: &str = "build/config/siso/backend_config/backend.star";
const SISOENV: &str = "build/config/siso/.sisoenv";
const SISORC: &str = "build/config/siso/.sisorc";
const BACKEND_CONFIG: &str = r#"# -*- bazel-starlark -*-
# Generated by Stainless for the opt-in, cache-only compile cache.
# Only clang compiles get a platform (from rewrapper_mac.cfg), so only they are
# looked up in or written to the action cache. Every other step stays local.

load("@builtin//struct.star", "module")

def __platform_properties(ctx):
    return {
        "default": {},
        "large": {},
    }

def __configs(ctx):
    return []

backend = module(
    "backend",
    platform_properties = __platform_properties,
    configs = __configs,
)
"#;

#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct Cache {
    pub(super) address: SocketAddr,
    pub(super) instance: String,
}

impl Cache {
    pub(super) fn from_env() -> Result<Option<Self>> {
        Self::from_values(
            std::env::var_os(ADDRESS_VARIABLE),
            std::env::var_os(INSTANCE_VARIABLE),
        )
    }

    fn from_values(address: Option<OsString>, instance: Option<OsString>) -> Result<Option<Self>> {
        let Some(address) = address.filter(|value| !value.is_empty()) else {
            ensure!(
                instance.is_none_or(|value| value.is_empty()),
                "{INSTANCE_VARIABLE} needs {ADDRESS_VARIABLE}; unset it for offline builds"
            );
            return Ok(None);
        };
        let address: SocketAddr = address
            .to_str()
            .and_then(|value| value.parse().ok())
            .filter(|value: &SocketAddr| value.ip().is_loopback() && value.port() != 0)
            .with_context(|| {
                format!(
                    "{ADDRESS_VARIABLE} must be a loopback IP and port, such as 127.0.0.1:9092. \
                    LAN or shared caches need TLS and are not supported"
                )
            })?;
        let instance = match instance.filter(|value| !value.is_empty()) {
            Some(value) => value
                .into_string()
                .ok()
                .filter(|value| value.len() <= 64 && is_token(value))
                .with_context(|| {
                    format!("{INSTANCE_VARIABLE} may only use letters, digits, '.', '_' and '-'")
                })?,
            None => DEFAULT_INSTANCE.to_owned(),
        };
        Ok(Some(Self { address, instance }))
    }

    pub(super) fn check_reachable(&self) -> Result<()> {
        TcpStream::connect_timeout(&self.address, Duration::from_secs(3)).with_context(|| {
            format!(
                "The compile cache at {} is not reachable. Start it (see docs/compile-cache.md), \
                or unset {ADDRESS_VARIABLE} to build offline",
                self.address
            )
        })?;
        Ok(())
    }

    // Siso flags. -j would set -remote_jobs under use_remoteexec, so pass -local_jobs.
    // The explicit address, CAS address, instance and project win over .sisoenv/.sisorc.
    pub(super) fn siso_arguments(&self, jobs: usize) -> Vec<String> {
        vec![
            format!("-local_jobs={jobs}"),
            "-re_exec_enable=false".to_owned(),
            "-re_cache_enable_read=true".to_owned(),
            "-re_cache_enable_write=true".to_owned(),
            format!("-reapi_address={}", self.address),
            "-reapi_cas_address=".to_owned(),
            format!("-reapi_instance={}", self.instance),
            "-reapi_insecure".to_owned(),
            "-project=".to_owned(),
        ]
    }

    fn sisoenv(&self) -> String {
        format!(
            "SISO_REAPI_INSTANCE={}\nSISO_REAPI_ADDRESS={}\n",
            self.instance, self.address
        )
    }

    pub(super) fn provenance(&self, salt: &Salt) -> Value {
        json!({
            "schema": SCHEMA,
            "address": self.address.to_string(),
            "instance": self.instance,
            "platform": salt.platform(),
        })
    }
}

pub(super) fn siso_arguments(cache: Option<&Cache>, jobs: usize) -> Vec<String> {
    cache.map_or_else(
        || vec!["-j".to_owned(), jobs.to_string()],
        |cache| cache.siso_arguments(jobs),
    )
}

/// Toolchain identity folded into the clang platform, so Xcode or SDK changes miss.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct Salt {
    xcode_build: String,
    sdk_build: String,
}

impl Salt {
    pub(super) fn new(xcodebuild_version: &str, sdk_build: &str) -> Result<Self> {
        let xcode_build = xcodebuild_version
            .lines()
            .find_map(|line| line.trim().strip_prefix("Build version "))
            .context("Cannot read the Xcode build version")?;
        Ok(Self {
            xcode_build: token(xcode_build, "Xcode build version")?,
            sdk_build: token(sdk_build, "macOS SDK build version")?,
        })
    }

    // rewrapper_cfg.star splits platform values on ',' and '=', so values are tokens.
    pub(super) fn platform(&self) -> String {
        format!(
            "OSFamily=Darwin,Arch=arm64,stainless-cache-schema={SCHEMA},stainless-xcode={},stainless-sdk={}",
            self.xcode_build, self.sdk_build
        )
    }
}

fn is_token(value: &str) -> bool {
    !value.is_empty()
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
}

fn token(value: &str, name: &str) -> Result<String> {
    let value = value.trim();
    ensure!(
        value.len() <= 64 && is_token(value),
        "Unexpected {name} for the compile cache: {value:?}"
    );
    Ok(value.to_owned())
}

/// The checked-in args with remote execution enabled. Siso still runs actions locally.
pub(super) fn cache_args(base: &str) -> Result<String> {
    let lines: Vec<&str> = base.lines().collect();
    ensure!(
        lines
            .iter()
            .filter(|line| line.trim() == OFFLINE_ARGS_LINE)
            .count()
            == 1
            && !base.contains(CACHE_ARGS_LINE),
        "chromium/args.gn must contain exactly one `{OFFLINE_ARGS_LINE}` line"
    );
    let mut result = String::new();
    for line in lines {
        result.push_str(if line.trim() == OFFLINE_ARGS_LINE {
            CACHE_ARGS_LINE
        } else {
            line
        });
        result.push('\n');
    }
    Ok(result)
}

/// Writes the cache profile after `gclient runhooks`, which restores the upstream
/// files on the next offline build.
pub(super) fn write_profile(
    source: &Path,
    output: &Path,
    cache: &Cache,
    salt: &Salt,
) -> Result<()> {
    ensure!(
        !source.join(SISORC).exists(),
        "Remove {} before using the compile cache; it can override cache flags",
        source.join(SISORC).display()
    );
    let rewrapper = source.join(REWRAPPER_CONFIG);
    fs::create_dir_all(rewrapper.parent().context("Invalid rewrapper path")?)?;
    fs::write(
        &rewrapper,
        format!(
            "platform={}\nremote_wrapper=\nexec_strategy=remote_local_fallback\n",
            salt.platform()
        ),
    )?;
    fs::write(source.join(BACKEND), BACKEND_CONFIG)?;
    fs::write(source.join(SISOENV), cache.sisoenv())?;
    fs::create_dir_all(output)?;
    fs::write(
        output.join(MARKER),
        serde_json::to_vec_pretty(&cache.provenance(salt))?,
    )?;
    Ok(())
}

/// Inherited Siso/RBE settings could redirect the project, binary or CAS endpoint.
pub(super) fn scrub_environment(command: &mut Command) {
    scrub(command, std::env::vars_os().map(|(key, _)| key));
}

fn scrub(command: &mut Command, inherited: impl IntoIterator<Item = OsString>) {
    for key in inherited {
        let name = key.to_string_lossy();
        if name.starts_with("SISO_") || name.starts_with("RBE_") {
            command.env_remove(&key);
        }
    }
}

/// Packaging and offline builds only accept output that never used the cache.
pub(super) fn require_uncached(output: &Path, build: Option<&Value>) -> Result<()> {
    ensure!(
        !output.join(MARKER).exists(),
        "{} was built with the compile cache; release builds must be uncached",
        output.display()
    );
    if let Some(build) = build {
        ensure!(
            build.get("reapi_cache").is_none_or(Value::is_null),
            "This build manifest records the compile cache; release builds must be uncached"
        );
    }
    Ok(())
}

#[derive(Debug, Default, PartialEq, Eq)]
pub(super) struct Report {
    pub(super) eligible: usize,
    pub(super) hits: usize,
    pub(super) writes: usize,
    pub(super) write_errors: usize,
}

impl Report {
    pub(super) fn parse(metrics: &str) -> Result<Self> {
        let mut report = Self::default();
        for line in metrics.lines().filter(|line| !line.trim().is_empty()) {
            let step: Value = serde_json::from_str(line).context("Malformed siso_metrics.json")?;
            let flag = |name: &str| step.get(name).and_then(Value::as_bool) == Some(true);
            let digest = step
                .get("digest")
                .and_then(Value::as_str)
                .is_some_and(|value| !value.is_empty());
            if digest || flag("cached") || flag("cache_write") || flag("cache_write_err") {
                report.eligible += 1;
            }
            report.hits += usize::from(flag("cached"));
            report.writes += usize::from(flag("cache_write"));
            report.write_errors += usize::from(flag("cache_write_err"));
        }
        Ok(report)
    }

    pub(super) fn summary(&self) -> String {
        let ratio = if self.eligible == 0 {
            0.0
        } else {
            self.hits as f64 * 100.0 / self.eligible as f64
        };
        format!(
            "Compile cache: {} of {} cacheable steps hit ({ratio:.1}%), {} results uploaded, {} uploads failed",
            self.hits, self.eligible, self.writes, self.write_errors
        )
    }
}

pub(super) fn report(output: &Path) -> Result<Report> {
    let path = output.join("siso_metrics.json");
    let report = Report::parse(
        &fs::read_to_string(&path)
            .with_context(|| format!("Cannot read Siso metrics at {}", path.display()))?,
    )?;
    println!("{}", report.summary());
    if report.write_errors > 0 {
        eprintln!(
            "Warning: {} compile cache uploads failed. The build is correct but partly uncached; \
            check that the cache server is still running and see siso.INFO in {}",
            report.write_errors,
            output.display()
        );
    }
    Ok(report)
}

pub(super) fn describe(cache: Option<&Cache>) -> String {
    match cache {
        None => format!("Compile cache: off ({ADDRESS_VARIABLE} unset; offline {OFFLINE_OUTPUT})"),
        Some(cache) => format!(
            "Compile cache: on, cache-only via {} instance {} into {CACHE_OUTPUT}",
            cache.address, cache.instance
        ),
    }
}

pub(super) fn reject_cache_for(command: &str, cache: Option<&Cache>) -> Result<()> {
    if cache.is_some() {
        bail!("{command} never uses the compile cache; unset {ADDRESS_VARIABLE}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::net::TcpListener;

    fn cache() -> Cache {
        Cache::from_values(Some("127.0.0.1:9092".into()), None)
            .unwrap()
            .unwrap()
    }

    fn salt() -> Salt {
        Salt::new("Xcode 27.2\nBuild version 27B52\n", "25C42\n").unwrap()
    }

    #[test]
    fn stays_offline_unless_a_loopback_cache_is_configured() {
        assert_eq!(Cache::from_values(None, None).unwrap(), None);
        assert_eq!(Cache::from_values(Some("".into()), None).unwrap(), None);
        assert!(Cache::from_values(None, Some("synthetic".into())).is_err());
        assert_eq!(siso_arguments(None, 8), ["-j", "8"]);
        assert_eq!(cache().instance, "stainless");
        let v6 = Cache::from_values(Some("[::1]:9092".into()), Some("synthetic-1.a_b".into()))
            .unwrap()
            .unwrap();
        assert_eq!(v6.address.to_string(), "[::1]:9092");
        assert_eq!(v6.instance, "synthetic-1.a_b");
        for address in [
            "192.0.2.10:9092",
            "0.0.0.0:9092",
            "localhost:9092",
            "127.0.0.1",
            "127.0.0.1:0",
            "grpc://127.0.0.1:9092",
        ] {
            assert!(
                Cache::from_values(Some(address.into()), None).is_err(),
                "{address}"
            );
        }
        for instance in ["projects/synthetic", "a,b", "a=b", "a b", &"x".repeat(65)] {
            assert!(
                Cache::from_values(Some("127.0.0.1:9092".into()), Some(instance.into())).is_err(),
                "{instance}"
            );
        }
    }

    #[test]
    fn maps_jobs_to_local_parallelism_and_pins_the_backend() {
        let arguments = cache().siso_arguments(6);
        assert!(arguments.contains(&"-local_jobs=6".to_owned()));
        assert!(
            !arguments
                .iter()
                .any(|argument| argument == "-j" || argument.starts_with("-remote_jobs"))
        );
        for expected in [
            "-re_exec_enable=false",
            "-re_cache_enable_read=true",
            "-re_cache_enable_write=true",
            "-reapi_address=127.0.0.1:9092",
            "-reapi_cas_address=",
            "-reapi_instance=stainless",
            "-reapi_insecure",
            "-project=",
        ] {
            assert!(arguments.contains(&expected.to_owned()), "{expected}");
        }
    }

    #[test]
    fn salts_the_clang_platform_with_sanitized_toolchain_builds() {
        assert_eq!(
            salt().platform(),
            "OSFamily=Darwin,Arch=arm64,stainless-cache-schema=1,stainless-xcode=27B52,stainless-sdk=25C42"
        );
        for pair in salt().platform().split(',') {
            assert_eq!(pair.split('=').count(), 2, "{pair}");
        }
        assert_ne!(
            Salt::new("Build version 27B53", "25C42")
                .unwrap()
                .platform(),
            salt().platform()
        );
        assert!(Salt::new("Xcode 27.2", "25C42").is_err());
        assert!(Salt::new("Build version 27B52,OSFamily=Linux", "25C42").is_err());
        assert!(Salt::new("Build version 27B52", "25C=42").is_err());
        assert!(Salt::new("Build version 27B52", "").is_err());
    }

    #[test]
    fn enables_remote_exec_only_in_generated_cache_args() {
        let base = "is_debug = false\nuse_remoteexec = false\nuse_system_xcode = true\n";
        assert_eq!(
            cache_args(base).unwrap(),
            "is_debug = false\nuse_remoteexec = true\nuse_system_xcode = true\n"
        );
        assert!(cache_args("is_debug = false\n").is_err());
        assert!(cache_args("use_remoteexec = false\nuse_remoteexec = false\n").is_err());
        assert!(cache_args("use_remoteexec = false\nuse_remoteexec = true\n").is_err());
        let checked_in = fs::read_to_string(
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../chromium/args.gn"),
        )
        .unwrap();
        assert!(
            cache_args(&checked_in)
                .unwrap()
                .contains("use_remoteexec = true\n")
        );
    }

    #[test]
    fn writes_a_clang_only_profile_without_a_cloud_project() {
        let fixture = tempfile::tempdir().unwrap();
        let source = fixture.path().join("src");
        let output = source.join(CACHE_OUTPUT);
        fs::create_dir_all(source.join("build/config/siso/backend_config")).unwrap();
        write_profile(&source, &output, &cache(), &salt()).unwrap();
        let rewrapper = fs::read_to_string(source.join(REWRAPPER_CONFIG)).unwrap();
        assert_eq!(
            rewrapper.lines().collect::<Vec<_>>(),
            [
                format!("platform={}", salt().platform()).as_str(),
                "remote_wrapper=",
                "exec_strategy=remote_local_fallback"
            ]
        );
        let backend = fs::read_to_string(source.join(BACKEND)).unwrap();
        assert!(backend.contains("\"default\": {},") && backend.contains("\"large\": {},"));
        assert!(!backend.contains("container-image") && !backend.contains("googlechrome"));
        let sisoenv = fs::read_to_string(source.join(SISOENV)).unwrap();
        assert_eq!(
            sisoenv,
            "SISO_REAPI_INSTANCE=stainless\nSISO_REAPI_ADDRESS=127.0.0.1:9092\n"
        );
        assert!(!sisoenv.contains("SISO_PROJECT") && !sisoenv.lines().any(str::is_empty));
        let marker: Value =
            serde_json::from_slice(&fs::read(output.join(MARKER)).unwrap()).unwrap();
        assert_eq!(marker["platform"], salt().platform());
        fs::write(source.join(SISORC), "ninja -reapi_address=192.0.2.10:443\n").unwrap();
        assert!(write_profile(&source, &output, &cache(), &salt()).is_err());
    }

    #[test]
    fn removes_inherited_siso_and_rbe_overrides() {
        let mut command = Command::new("/usr/bin/true");
        scrub(
            &mut command,
            [
                "SISO_PROJECT",
                "SISO_REAPI_CAS_ADDRESS",
                "SISO_PATH",
                "RBE_service_no_security",
                "PATH",
                "HOME",
            ]
            .map(OsString::from),
        );
        let removed: Vec<_> = command
            .get_envs()
            .filter(|(_, value)| value.is_none())
            .map(|(key, _)| key.to_string_lossy().into_owned())
            .collect();
        assert_eq!(
            removed.len(),
            4,
            "only Siso/RBE variables are removed: {removed:?}"
        );
        assert!(!removed.iter().any(|key| key == "PATH" || key == "HOME"));
    }

    #[test]
    fn packaging_rejects_cache_outputs_even_after_an_offline_build() {
        let fixture = tempfile::tempdir().unwrap();
        let source = fixture.path().join("src");
        let cached = source.join(CACHE_OUTPUT);
        let offline = source.join(OFFLINE_OUTPUT);
        fs::create_dir_all(source.join("build/config/siso/backend_config")).unwrap();
        write_profile(&source, &cached, &cache(), &salt()).unwrap();
        fs::create_dir_all(&offline).unwrap();
        let clean = json!({"schema_version": 1});
        require_uncached(&offline, Some(&clean)).unwrap();
        assert!(require_uncached(&cached, Some(&clean)).is_err());
        let recorded = json!({"reapi_cache": cache().provenance(&salt())});
        assert!(require_uncached(&offline, Some(&recorded)).is_err());
        fs::copy(cached.join(MARKER), offline.join(MARKER)).unwrap();
        assert!(require_uncached(&offline, None).is_err());
        assert!(reject_cache_for("package", Some(&cache())).is_err());
        reject_cache_for("package", None).unwrap();
    }

    #[test]
    fn reports_hits_uploads_and_failed_uploads() {
        let metrics = r#"{"rule":"clang/cxx","digest":"a/1","cached":true}
{"rule":"clang/cxx","digest":"b/1","cache_write":true}
{"rule":"clang/cxx","digest":"c/1","cache_write_err":true}
{"rule":"rust/rustc"}

{"rule":"stamp","no_exec":true}
"#;
        let report = Report::parse(metrics).unwrap();
        assert_eq!(
            report,
            Report {
                eligible: 3,
                hits: 1,
                writes: 1,
                write_errors: 1
            }
        );
        assert!(
            report
                .summary()
                .contains("1 of 3 cacheable steps hit (33.3%)")
        );
        assert!(Report::parse("{not json").is_err());
    }

    #[test]
    fn fails_clearly_when_the_cache_is_down() {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        let cache = Cache::from_values(
            Some(listener.local_addr().unwrap().to_string().into()),
            None,
        )
        .unwrap()
        .unwrap();
        cache.check_reachable().unwrap();
        drop(listener);
        let error = format!("{:#}", cache.check_reachable().unwrap_err());
        assert!(
            error.contains("unset STAINLESS_REAPI_ADDRESS to build offline"),
            "{error}"
        );
    }
}
